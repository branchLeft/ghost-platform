CREATE TABLE "portal"."demo_request" (
	"demo_id" uuid PRIMARY KEY NOT NULL,
	"verified_subject" text NOT NULL,
	"verified_address" text NOT NULL,
	"publication_name" text NOT NULL,
	"description" text,
	"accent_colour" text,
	"theme" text,
	"font" text,
	"new_to_ghost" boolean NOT NULL,
	"import_source" text,
	"outlet_type" text NOT NULL,
	"logo_hash" text,
	"consent_wording" text NOT NULL,
	"explainer_wording" text NOT NULL,
	"submitted_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "demo_request_verified_address_unique" UNIQUE("verified_address"),
	CONSTRAINT "demo_request_address_shape" CHECK ("portal"."demo_request"."verified_address" = lower("portal"."demo_request"."verified_address") AND char_length("portal"."demo_request"."verified_address") <= 254 AND "portal"."demo_request"."verified_address" ~ '^[^@[:space:]]+@[^@[:space:]]+[.][^@[:space:]]+$'),
	CONSTRAINT "demo_request_subject_length" CHECK (char_length("portal"."demo_request"."verified_subject") BETWEEN 1 AND 255),
	CONSTRAINT "demo_request_name_length" CHECK (char_length("portal"."demo_request"."publication_name") BETWEEN 1 AND 100),
	CONSTRAINT "demo_request_description_length" CHECK ("portal"."demo_request"."description" IS NULL OR char_length("portal"."demo_request"."description") BETWEEN 1 AND 500),
	CONSTRAINT "demo_request_colour_shape" CHECK ("portal"."demo_request"."accent_colour" IS NULL OR "portal"."demo_request"."accent_colour" ~ '^#[0-9a-f]{6}$'),
	CONSTRAINT "demo_request_choices_shape" CHECK (("portal"."demo_request"."theme" IS NULL OR "portal"."demo_request"."theme" ~ '^[a-z0-9-]{1,40}$') AND ("portal"."demo_request"."font" IS NULL OR "portal"."demo_request"."font" ~ '^[a-z0-9-]{1,40}$') AND "portal"."demo_request"."outlet_type" ~ '^[a-z0-9-]{1,40}$'),
	CONSTRAINT "demo_request_import_source_length" CHECK ("portal"."demo_request"."import_source" IS NULL OR char_length("portal"."demo_request"."import_source") BETWEEN 1 AND 100),
	CONSTRAINT "demo_request_logo_hash_shape" CHECK ("portal"."demo_request"."logo_hash" IS NULL OR "portal"."demo_request"."logo_hash" ~ '^[0-9a-f]{64}$'),
	CONSTRAINT "demo_request_wording_length" CHECK (char_length("portal"."demo_request"."consent_wording") BETWEEN 1 AND 2000 AND char_length("portal"."demo_request"."explainer_wording") BETWEEN 1 AND 2000)
);
